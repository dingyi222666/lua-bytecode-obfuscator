#!/usr/bin/env python3
"""Generates the JS delivery of the bundled decoder stub chunks.

The decoder assets ship with the feature modules as JVM classpath resources
(:lua-obfuscation-strings /obfuscator/decode_NN.luac and
:lua-obfuscation-constants /obfuscator/decode_num_NN.luac). A browser cannot
read classpath resources, so the js runtime (:lua-runtime-js) carries the same
bytes as committed base64 constants. This script is the single source of truth
linking both deliveries: it reads the JVM resources and regenerates

    lua-runtime-js/src/jsMain/kotlin/io/github/dingyi222666/luabytecode/runtime/js/LuaDecoderAssetsJs.kt

The md5 digests it emits are asserted on the JVM side by the
DecoderAssetIntegrityTest of both feature modules and on the js side by the
LuaDecoderAssetsJsTest of :lua-runtime-js — editing any .luac without
regenerating breaks the build.

Usage: python3 tools/generate-js-decoder-assets.py
"""

import base64
import hashlib
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

ASSETS = {
    "/obfuscator/decode_53.luac":
        ROOT / "lua-obfuscation-strings/src/jvmMain/resources/obfuscator/decode_53.luac",
    "/obfuscator/decode_54.luac":
        ROOT / "lua-obfuscation-strings/src/jvmMain/resources/obfuscator/decode_54.luac",
    "/obfuscator/decode_55.luac":
        ROOT / "lua-obfuscation-strings/src/jvmMain/resources/obfuscator/decode_55.luac",
    "/obfuscator/decode_num_53.luac":
        ROOT / "lua-obfuscation-constants/src/jvmMain/resources/obfuscator/decode_num_53.luac",
    "/obfuscator/decode_num_54.luac":
        ROOT / "lua-obfuscation-constants/src/jvmMain/resources/obfuscator/decode_num_54.luac",
    "/obfuscator/decode_num_55.luac":
        ROOT / "lua-obfuscation-constants/src/jvmMain/resources/obfuscator/decode_num_55.luac",
}

TARGET = (ROOT /
          "lua-runtime-js/src/jsMain/kotlin/io/github/dingyi222666/luabytecode/runtime/js/LuaDecoderAssetsJs.kt")

HEADER = """\
// GENERATED by tools/generate-js-decoder-assets.py — DO NOT EDIT BY HAND.
// Regenerate after changing any bundled decoder .luac asset:
//   python3 tools/generate-js-decoder-assets.py
//
// Source of truth: the jvmMain resources of :lua-obfuscation-strings
// (/obfuscator/decode_NN.luac) and :lua-obfuscation-constants
// (/obfuscator/decode_num_NN.luac). The md5 digests below are asserted on the
// JVM side by the DecoderAssetIntegrityTest of both feature modules and on
// the js side by :lua-runtime-js LuaDecoderAssetsJsTest, so the two deliveries
// cannot drift apart silently.
package io.github.dingyi222666.luabytecode.runtime.js

import kotlin.io.encoding.Base64

"""


def main() -> None:
    blobs = {}
    digests = {}
    for path, file in ASSETS.items():
        data = file.read_bytes()
        blobs[path] = base64.b64encode(data).decode("ascii")
        digests[path] = hashlib.md5(data).hexdigest()
        print(f"{path}: {len(data)} bytes md5={digests[path]}")

    def klist(name, values, value_fmt=str):
        lines = [f"    val {name}: List<String> = listOf("]
        lines += [f'        "{v}",' for v in values]
        lines.append("    )")
        return "\n".join(lines)

    entries = "\n".join(
        f'        "{p}" to "{digests[p]}",' for p in ASSETS)
    b64_entries = "\n".join(f'        "{p}" to "{blobs[p]}",' for p in ASSETS)

    body = f"""/**
 * JS delivery of the bundled decoder stub chunks (roadmap step 6). The
 * strings / constants passes load these through `Platform.bundledChunks`
 * exactly like on the JVM — only the transport differs (committed base64
 * constants instead of classpath resources, see [JsPlatform]).
 *
 * Bytes are identical to the JVM classpath assets; the digests are pinned by
 * tests on both platforms.
 */
object LuaDecoderAssetsJs {{

{klist("paths", list(ASSETS.keys()))}

    /** Lowercase md5 hex of every asset, keyed by resource path. */
    val md5HexByPath: Map<String, String> = mapOf(
{entries}
    )

    private val base64ByPath: Map<String, String> = mapOf(
{b64_entries}
    )

    /**
     * Loads the bundled asset [path] (e.g. `/obfuscator/decode_54.luac`),
     * `null` when the path is not bundled — same contract as the JVM
     * classpath `BundledChunkSource`.
     */
    fun load(path: String): ByteArray? {{
        val encoded = base64ByPath[path] ?: return null
        return Base64.decode(encoded)
    }}
}}
"""
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(HEADER + body)
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
